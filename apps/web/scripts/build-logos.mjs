// Writes monochrome brand marks for the ranked brands to public/logos/<slug>.svg
// and the list of available slugs to lib/brand-logos.ts.
//
//   npm run logos
//
// Source: Simple Icons (https://simpleicons.org), CC0 1.0. The marks are
// trademarks of their owners and are shown only to identify the brand a
// statistic is about. Brands without an official mark in Simple Icons (e.g.
// Mercedes-Benz) get a typographic monogram instead; nothing is redrawn.

import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import * as icons from "simple-icons";
import { svgPathBbox } from "svg-path-bbox";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");

// Our brand slug (lib/data, ingestion) → Simple Icons slug.
const BRANDS = {
  "aston-martin": "astonmartin",
  audi: "audi",
  bentley: "bentley",
  bmw: "bmw",
  cadillac: "cadillac",
  chevrolet: "chevrolet",
  chrysler: "chrysler",
  citroen: "citroen",
  dacia: "dacia",
  daf: "daf",
  ds: "dsautomobiles",
  ferrari: "ferrari",
  fiat: "fiat",
  ford: "ford",
  honda: "honda",
  hyundai: "hyundai",
  infiniti: "infiniti",
  iveco: "iveco",
  jeep: "jeep",
  kia: "kia",
  lada: "lada",
  lamborghini: "lamborghini",
  man: "man",
  maserati: "maserati",
  mazda: "mazda",
  mg: "mg",
  mini: "mini",
  mitsubishi: "mitsubishi",
  nissan: "nissan",
  opel: "opel",
  peugeot: "peugeot",
  polestar: "polestar",
  porsche: "porsche",
  ram: "ram",
  renault: "renault",
  "rolls-royce": "rollsroyce",
  scania: "scania",
  seat: "seat",
  skoda: "skoda",
  smart: "smart",
  subaru: "subaru",
  suzuki: "suzuki",
  tesla: "tesla",
  toyota: "toyota",
  volkswagen: "volkswagen",
  volvo: "volvo",
};

const bySlug = new Map(Object.values(icons).filter((icon) => icon && icon.slug).map((icon) => [icon.slug, icon]));
const out = path.join(root, "public", "logos");
await mkdir(out, { recursive: true });

const written = [];
for (const [slug, source] of Object.entries(BRANDS)) {
  const icon = bySlug.get(source);
  if (!icon) throw new Error(`simple-icons has no "${source}" (for ${slug})`);
  await writeFile(path.join(out, `${slug}.svg`), icon.svg.replace("<svg ", '<svg fill="#000" '), "utf8");
  // Marks fill their 24px box along the longer side, so a wordmark (Kia, Audi)
  // reads much smaller than an emblem. Scale wide marks up for equal weight.
  const [x0, y0, x1, y1] = svgPathBbox(icon.path);
  const aspect = Math.max(x1 - x0, y1 - y0) / Math.max(0.01, Math.min(x1 - x0, y1 - y0));
  const scale = Math.round(Math.min(1.5, Math.max(1, aspect ** 0.32)) * 100) / 100;
  written.push({ slug, title: icon.title, guidelines: icon.guidelines ?? null, scale });
}

const notice = [
  "# Brand marks",
  "",
  "Generated by `npm run logos` from Simple Icons (https://simpleicons.org), released under CC0 1.0.",
  "The marks are trademarks of their respective owners. Autostatistika shows them only to identify the",
  "brand a statistic refers to; it is not affiliated with or endorsed by any of them.",
  "",
  ...written.map((entry) => `- ${entry.slug}: ${entry.title}${entry.guidelines ? ` (guidelines: ${entry.guidelines})` : ""}`),
  "",
].join("\n");
await writeFile(path.join(out, "NOTICE.md"), notice, "utf8");

const list = written.map((entry) => `  ["${entry.slug}", ${entry.scale}],`).join("\n");
await writeFile(
  path.join(root, "lib", "brand-logos.ts"),
  "// Generated by scripts/build-logos.mjs: brands with a mark in public/logos/ and\n" +
    "// the scale that gives wide wordmarks the same visual weight as round emblems.\n" +
    `export const BRAND_LOGOS: ReadonlyMap<string, number> = new Map([\n${list}\n]);\n`,
  "utf8",
);
console.log(`${written.length} logos written to public/logos`);
