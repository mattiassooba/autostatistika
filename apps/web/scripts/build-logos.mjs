  dacia: "dacia",
  daf: "daf",
  ds: "dsautomobiles",
  ferrari: "ferrari",
  fiat: "fiat",
  ford: "ford",
  honda: "honda",
  hyundai: "hyundai",
  infiniti: "infiniti",
  iveco: "iveco",
  jeep: "jeep",
  kia: "kia",
  lada: "lada",
  lamborghini: "lamborghini",
  man: "man",
  maserati: "maserati",
  mazda: "mazda",
  mg: "mg",
  mini: "mini",
  mitsubishi: "mitsubishi",
  nissan: "nissan",
  opel: "opel",
  peugeot: "peugeot",
  polestar: "polestar",
  porsche: "porsche",
  ram: "ram",
  renault: "renault",
  "rolls-royce": "rollsroyce",
