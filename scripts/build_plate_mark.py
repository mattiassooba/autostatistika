"""Outline the plate mark's lettering into apps/web/lib/brand/plate-mark-paths.ts.

The site mark (AUTOSTATISTIKA.EE on a registration-plate shape) is drawn as SVG
paths, so it never waits for a web font and renders the same in the header,
the Open Graph images and anywhere else an SVG goes. This script shapes the
text with HarfBuzz (kerning included) at the approved Archivo settings and
writes the outlines in plate units: the plate is 100 units tall.

Needs fonttools, brotli and uharfbuzz (dev only, not in requirements.txt):

    pip install fonttools brotli uharfbuzz
    python scripts/build_plate_mark.py path/to/Archivo-variable.(ttf|woff2)

Archivo is the variable font (wdth 62-125, wght 100-900) the site loads from
Google Fonts via next/font, licensed under the SIL Open Font License. The
latin woff2 from a production build (apps/web/out/_next/static/media) works.
"""

from __future__ import annotations

import io
import sys
from pathlib import Path

import uharfbuzz as hb
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

OUT = Path(__file__).resolve().parents[1] / "apps/web/lib/brand/plate-mark-paths.ts"

# Wordmark: AUTOSTATISTIKA at weight 720 and .EE at 460, both at width 74 and
# 70 units, starting at x=66 on a 74.15 baseline. Like SVG textLength with
# lengthAdjust="spacing", the run is tracked out evenly to exactly 576 units.
WORD = {"x": 66.0, "baseline": 74.15, "size": 70.0, "length": 576.0}
RUNS = [("AUTOSTATISTIKA", {"wdth": 74, "wght": 720}), (".EE", {"wdth": 74, "wght": 460})]

# Country strip letters, centred in the strip. "lg" is the master for marks 40
# px tall and up; "sm" (header sizes) has larger, narrower letters.
STRIP = {
    "lg": {"cx": 21.5, "baseline": 57.6, "size": 22.0, "axes": {"wdth": 90, "wght": 700}},
    "sm": {"cx": 22.0, "baseline": 59.3, "size": 27.0, "axes": {"wdth": 78, "wght": 720}},
}


def load_face(path: Path) -> tuple[hb.Face, int]:
    font = TTFont(str(path))
    font.flavor = None
    buffer = io.BytesIO()
    font.save(buffer)
    data = buffer.getvalue()
    return hb.Face(hb.Blob(data)), font["head"].unitsPerEm


def shape(face: hb.Face, text: str, axes: dict[str, float]) -> tuple[hb.Font, list[tuple[int, int]]]:
    font = hb.Font(face)
    font.set_variations(axes)
    buf = hb.Buffer()
    buf.add_str(text)
    buf.guess_segment_properties()
    hb.shape(font, buf, {"kern": True, "liga": False})
    glyphs = [(info.codepoint, pos.x_advance) for info, pos in zip(buf.glyph_infos, buf.glyph_positions)]
    return font, glyphs


def outline(font: hb.Font, gid: int, scale: float, x: float, baseline: float) -> str:
    pen = SVGPathPen(None, ntos=lambda value: f"{value:.2f}".rstrip("0").rstrip("."))
    font.draw_glyph_with_pen(gid, TransformPen(pen, (scale, 0, 0, -scale, x, baseline)))
    return pen.getCommands()


def word_paths(face: hb.Face, upem: int) -> tuple[str, str]:
    scale = WORD["size"] / upem
    shaped = [(shape(face, text, axes), text) for text, axes in RUNS]
    natural = sum(advance for (_, glyphs), _ in shaped for _, advance in glyphs) * scale
    count = sum(len(glyphs) for (_, glyphs), _ in shaped)
    tracking = (WORD["length"] - natural) / (count - 1)
    x = WORD["x"]
    out = []
    for (font, glyphs), _ in shaped:
        parts = []
        for gid, advance in glyphs:
            parts.append(outline(font, gid, scale, x, WORD["baseline"]))
            x += advance * scale + tracking
        out.append("".join(parts))
    return out[0], out[1]


def strip_path(face: hb.Face, upem: int, spec: dict) -> str:
    scale = spec["size"] / upem
    font, glyphs = shape(face, "EE", spec["axes"])
    width = sum(advance for _, advance in glyphs) * scale
    x = spec["cx"] - width / 2
    parts = []
    for gid, advance in glyphs:
        parts.append(outline(font, gid, scale, x, spec["baseline"]))
        x += advance * scale
    return "".join(parts)


def main() -> None:
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    face, upem = load_face(Path(sys.argv[1]))
    name, domain = word_paths(face, upem)
    lines = [
        "// Generated by scripts/build_plate_mark.py from Archivo (SIL Open Font License).",
        "// Plate units: the plate is 100 units tall. Do not edit by hand.",
        "",
        f'export const NAME_PATH = "{name}";',
        f'export const DOMAIN_PATH = "{domain}";',
        f'export const STRIP_PATH = {{ lg: "{strip_path(face, upem, STRIP["lg"])}", sm: "{strip_path(face, upem, STRIP["sm"])}" }} as const;',
        "",
    ]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(Path.cwd()) if OUT.is_relative_to(Path.cwd()) else OUT}")


if __name__ == "__main__":
    main()
